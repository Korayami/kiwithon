def discover_templates(template_dir: Path, extensions: tuple[str, ...]) -> list[tuple[str, Path]]:
    """Return sorted list of (posix_rel_name, full_path) for all templates in template_dir."""
    found: list[tuple[str, Path]] = []
    if not template_dir.exists():
        return found
    for root, dirs, files in os.walk(template_dir):
        dirs.sort()
        for fname in sorted(files):
            if fname.endswith(extensions):
                full_path = Path(root) / fname
                rel_name = full_path.relative_to(template_dir).as_posix()
                found.append((rel_name, full_path))
    return found


def compile_templates_to_module(
    template_dirs: list[Path],
    output_file: Path,
    extensions: tuple[str, ...] = (".html", ".j2", ".jinja2", ".txt", ".xml"),
) -> int:
    """Compile all templates under `template_dirs` into `output_file`.

    Returns the number of compiled templates.
    """
    try:
        import jinja2
    except ImportError:
        # Provide a minimal fallback compiler if jinja2 is not installed in the build host venv
        jinja2 = None

    env = None
    if jinja2 is not None:
        env = jinja2.Environment(
            autoescape=True,
             extensions=["jinja2.ext.do", "jinja2.ext.loopcontrols"],
        )

    templates_map: dict[str, str] = {}
    for tdir in template_dirs:
        for rel_name, full_path in discover_templates(tdir, extensions):
            source = full_path.read_text(encoding="utf-8")
            if env is not None:
                compiled_py = env.compile(
                    source,
                    name=rel_name,
                    filename=f"<kiwi_template:{rel_name}>",
                    raw=True,
                )
            else:
                # Fallback stub that compiles via environment at runtime if host lacked jinja2
                compiled_py = (
                    "from jinja2.runtime import LoopContext, Macro, Markup, Namespace, TemplateNotFound, "
                    "TemplateReference, TemplateRuntimeError, Undefined, escape, identity, internalcode, "
                    "markup_join, missing, str_join\n"
                    f"_RAW_SOURCE = {source!r}\n"
                    "def root(context, missing=missing):\n"
                    "    resolve = context.resolve_or_missing\n"
                    "    yield from context.environment.from_string(_RAW_SOURCE).root_render_func(context)\n"
                    "blocks = {}\n"
                    "debug_info = ''\n"
                )
            templates_map[rel_name] = compiled_py

    output_file.parent.mkdir(parents=True, exist_ok=True)
    lines = [LOADER_PROLOGUE, "\n# --- Precompiled Template Registry ---\n"]
    for rel_name in sorted(templates_map.keys()):
        py_src = templates_map[rel_name]
        lines.append(f"_register_template({rel_name!r}, {py_src!r})\n")

    lines.append(
        "\ndef warmup_all_templates(environment: jinja2.Environment) -> int:\n"
        "    \"\"\"Eagerly compile and bind all precompiled templates prior to heap immortalization.\"\"\"\n"
        "    loader = KiwiPrecompiledLoader()\n"
        "    count = 0\n"
        "    for name in _TEMPLATES:\n"
        "        loader.load(environment, name)\n"
        "        count += 1\n"
        "    return count\n"
    )

    output_file.write_text("".join(lines), encoding="utf-8")
    return len(templates_map)


def resolve_template_dirs(app_dir: Path) -> list[Path]:
    """Locate template directories inside a KiwiSpaceONE or general Flask/Quart app."""
    candidates = [
        app_dir / "templates",
        app_dir / "src" / "kiwispaceone" / "templates",
        app_dir / "src" / "templates",
        app_dir / "kiwispaceone" / "templates",
    ]
    found = [p for p in candidates if p.is_dir()]
    if not found and app_dir.is_dir():
        # Check if app_dir itself is a templates directory
        if any(app_dir.glob("**/*.html")) or any(app_dir.glob("**/*.j2")):
            found.append(app_dir)
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="AOT-compile Jinja2 templates into _kiwi_precompiled_templates.py"
    )
    parser.add_argument(
        "app_dir",
        nargs="?",
        default=os.environ.get("KIWITHON_APP_DIR", "."),
        help="Path to the application directory or templates folder (default: $KIWITHON_APP_DIR or '.')",
    )
    parser.add_argument(
        "-o",
        "--output",
        default=None,
        help="Output path for _kiwi_precompiled_templates.py (default: <app_dir>/build/_kiwi_precompiled_templates.py)",
    )
    args = parser.parse_args(argv)

    app_dir = Path(args.app_dir).resolve()
    if args.output:
        output_file = Path(args.output).resolve()
    else:
        output_file = app_dir / "build" / "_kiwi_precompiled_templates.py"

    template_dirs = resolve_template_dirs(app_dir)
    count = compile_templates_to_module(template_dirs, output_file)
    print(f"[compile_jinja] Compiled {count} templates from {len(template_dirs)} dir(s) -> {output_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
